// Generates src/lib/app-inventory.ts: a factual map of what the repo actually
// contains right now — every API route + its HTTP methods, every page, every
// Prisma model + fields, and the lib/ helpers. Derived directly from the source
// on every build, so it can never drift out of date (unlike hand-written prose).
// Fed to Claude alongside ARCHITECTURE.md when estimating idea scope / writing
// build prompts, so it never invents or duplicates something that exists.
import { readFileSync, writeFileSync, readdirSync, statSync, mkdirSync } from "node:fs";
import { join, dirname, relative, sep } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const appDir = join(root, "src", "app");
const schemaPath = join(root, "prisma", "schema.prisma");
const libDir = join(root, "src", "lib");
const outPath = join(root, "src", "lib", "app-inventory.ts");

function walk(dir) {
  let out = [];
  let entries;
  try {
    entries = readdirSync(dir);
  } catch {
    return out;
  }
  for (const e of entries) {
    const p = join(dir, e);
    let s;
    try {
      s = statSync(p);
    } catch {
      continue;
    }
    if (s.isDirectory()) out = out.concat(walk(p));
    else out.push(p);
  }
  return out;
}

// Turn an app-relative file path into its Next.js route, dropping the trailing
// route.ts/page.tsx and any (route group) segments.
function toRoute(relToApp) {
  const segs = relToApp
    .split("/")
    .slice(0, -1)
    .filter((s) => !(s.startsWith("(") && s.endsWith(")")));
  const path = "/" + segs.join("/");
  return path.length > 1 ? path.replace(/\/$/, "") : "/";
}

const files = walk(appDir);

// API routes with their exported HTTP methods.
const routes = [];
for (const f of files) {
  if (!f.endsWith(`${sep}route.ts`) && !f.endsWith(`${sep}route.tsx`)) continue;
  const rel = relative(appDir, f).split(sep).join("/");
  const src = readFileSync(f, "utf8");
  const methods = ["GET", "POST", "PUT", "PATCH", "DELETE"].filter((m) =>
    new RegExp(`export\\s+(async\\s+)?function\\s+${m}\\b`).test(src)
  );
  routes.push(`${toRoute(rel)} [${methods.join(", ")}]`);
}
routes.sort();

// Pages.
const pages = [];
for (const f of files) {
  if (!f.endsWith(`${sep}page.tsx`)) continue;
  const rel = relative(appDir, f).split(sep).join("/");
  pages.push(toRoute(rel));
}
pages.sort();

// Prisma models + fields (name + type, skipping block attributes/comments).
const models = [];
try {
  const schema = readFileSync(schemaPath, "utf8");
  const re = /model\s+(\w+)\s+\{([^}]*)\}/g;
  let m;
  while ((m = re.exec(schema))) {
    const fields = m[2]
      .split("\n")
      .map((l) => l.trim())
      .filter((l) => l && !l.startsWith("@@") && !l.startsWith("//"))
      .map((l) => {
        const parts = l.split(/\s+/);
        return `${parts[0]}${parts[1] ? " " + parts[1] : ""}`;
      });
    models.push(`${m[1]}: ${fields.join(", ")}`);
  }
} catch {
  /* schema optional */
}

let libs = [];
try {
  libs = readdirSync(libDir)
    .filter((f) => f.endsWith(".ts"))
    .sort();
} catch {
  /* lib optional */
}

const inventory = [
  "## Live code inventory (auto-generated from the repo at build time — the definitive list of what exists RIGHT NOW; trust this over any prose if they disagree)",
  "",
  "### API routes — path [methods]",
  ...routes.map((r) => `- ${r}`),
  "",
  "### Pages",
  ...pages.map((p) => `- ${p}`),
  "",
  "### Prisma models — Model: field type, …",
  ...models.map((m) => `- ${m}`),
  "",
  "### lib/ helpers",
  `- ${libs.join(", ")}`,
].join("\n");

const banner =
  "// AUTO-GENERATED by scripts/gen-app-inventory.mjs from the repo source.\n" +
  "// Do not edit by hand — it is regenerated on every build.\n";

mkdirSync(dirname(outPath), { recursive: true });
writeFileSync(outPath, `${banner}export const APP_INVENTORY = ${JSON.stringify(inventory)};\n`);
console.log(
  `gen-app-inventory: wrote ${outPath} (${routes.length} routes, ${pages.length} pages, ${models.length} models)`
);
